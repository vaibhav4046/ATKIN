#!/usr/bin/env node
/**
 * Regenerate src/content/assetDigests.generated.ts
 *
 * Every digest ATKIN shows to a user as proof must be the real SHA-256 of the
 * artifact actually shipped. This script computes them from disk so the values
 * cannot be hand-edited into fiction.
 *
 * src/tests/assetDigestIntegrity.test.ts recomputes these values and fails if
 * the committed constants drift from the files, so a stale digest cannot ship.
 *
 * Usage: node scripts/gen-asset-digests.mjs
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

/** Artifacts whose digests are surfaced in the product UI as verification. */
const TRACKED = [
  {
    key: 'canonicalMark',
    file: 'public/brand/atkin-mark.png',
    label: 'Canonical ATKIN mark shipped at /brand/atkin-mark.png',
  },
  {
    key: 'advocateMark',
    file: 'public/atkin/characters/atkin-character-files.webp',
    label: 'Sovereign Advocate artwork shown in the hero verification card',
  },
  {
    key: 'demoContractFixture',
    file: 'fixtures/test-contract-independent.txt',
    label: 'Alder Peak demo contract fixture (the source shown in Product Proof)',
  },
];

function sha256(absPath) {
  return createHash('sha256').update(readFileSync(absPath)).digest('hex');
}

const entries = TRACKED.map(({ key, file, label }) => {
  const abs = join(root, file);
  let digest;
  try {
    digest = sha256(abs);
  } catch (err) {
    console.error(`FATAL: cannot read tracked artifact ${file}: ${err.message}`);
    process.exit(1);
  }
  return { key, file: relative(root, abs).split('\\').join('/'), label, digest };
});

const body = `/**
 * AUTO-GENERATED by scripts/gen-asset-digests.mjs — do not edit by hand.
 *
 * Regenerate:  node scripts/gen-asset-digests.mjs
 * Enforced by:  src/tests/assetDigestIntegrity.test.ts
 *
 * These are the real SHA-256 digests of the artifacts ATKIN ships. The landing
 * page presents them as verification, so they must never be invented.
 */
export interface AssetDigest {
  /** Repo-relative path of the artifact. */
  readonly file: string;
  /** Human description of what the digest covers. */
  readonly label: string;
  /** Real lowercase hex SHA-256 of the file bytes. */
  readonly sha256: string;
  /** Artifact size in bytes, shown alongside the digest. */
  readonly bytes: number;
}

export const ASSET_DIGESTS = {
${entries
  .map(
    (e) => `  ${e.key}: {
    file: '${e.file}',
    label: '${e.label.replace(/'/g, "\\'")}',
    sha256: '${e.digest}',
    bytes: ${readFileSync(join(root, e.file)).length},
  } as const,`
  )
  .join('\n')}
} as const satisfies Record<string, AssetDigest>;

export type AssetDigestKey = keyof typeof ASSET_DIGESTS;
`;

const outFile = join(root, 'src', 'content', 'assetDigests.generated.ts');
writeFileSync(outFile, body, 'utf8');

for (const e of entries) {
  console.log(`  ${e.digest}  ${e.file}`);
}
console.log(`\nWrote ${relative(root, outFile).split('\\').join('/')}`);
